def load_events(directory: Path, root: Path, tag: str = EVAL_TAG) -> dict:
    """Read every event file of one run, keeping replayed evaluations and their provenance.

    A resumed run can log the same step twice; the evaluation with the latest wall time is kept, the
    others are listed as superseded, and two replays may not differ by more than two percentage points.
    """
    from tensorboard.backend.event_processing.event_accumulator import EventAccumulator

    files = sorted(require_dir(directory).glob("events.out.tfevents.*"))
    if not files:
        raise FileNotFoundError(f"No event files in {directory}")
    points = []
    for path in files:
        acc = EventAccumulator(str(path), size_guidance={"scalars": 0}, purge_orphaned_data=False).Reload()
        if tag in acc.Tags()["scalars"]:
            points.extend(dict(step=e.step, value=e.value, wall_time=e.wall_time, source=path.name)
                          for e in acc.Scalars(tag))
    by_step, superseded = {}, []
    for point in sorted(points, key=lambda p: (p["wall_time"], p["source"])):
        previous = by_step.get(point["step"])
        if previous is not None:
            if abs(previous["value"] - point["value"]) > .02:
                raise ValueError(f"Replayed evaluation differs by over two points: {directory} step {point['step']}")
            superseded.append(previous)
        by_step[point["step"]] = point
    points = [by_step[k] for k in sorted(by_step)]
    if not points or any(p["step"] <= 0 or not np.isfinite(p["value"]) or not 0 <= p["value"] <= 1 for p in points):
        raise ValueError(f"Missing or invalid held-out evaluations: {directory}")
    return dict(points=points, superseded=superseded,
                sources=[dict(path=relative(p, root), bytes=p.stat().st_size, sha256=sha256_bytes(p.read_bytes()))
                         for p in files])


def average_runs(runs: list) -> dict:
    """Equal-weight mean over distinct training seeds at the evaluation steps every seed completed."""
    if not runs or len({run["seed"] for run in runs}) != len(runs):
        raise ValueError("Seed averages require nonempty runs with distinct seeds")
    by_seed = {}
    for run in runs:
        values = {p["step"]: p["value"] for p in run["points"]}
        if (not values or len(values) != len(run["points"])
                or any(s <= 0 or not np.isfinite(v) or not 0 <= v <= 1 for s, v in values.items())):
            raise ValueError("Each seed needs unique positive steps and finite accuracies in [0, 1]")
        by_seed[run["seed"]] = values
    common = sorted(set.intersection(*(set(v) for v in by_seed.values())))
    if len(common) < 2:
        raise ValueError("Seed averages require at least two shared evaluation steps")
    points = []
    for step in common:
        values = [v[step] for v in by_seed.values()]
        points.append(dict(step=step, value=float(np.mean(values)), n=len(values),
                           sample_std=float(np.std(values, ddof=1)) if len(values) > 1 else None,
                           values_by_seed={str(seed): v[step] for seed, v in by_seed.items()}))
    return dict(seeds=sorted(by_seed), points=points,
                excluded_steps_by_seed={str(seed): sorted(set(v) - set(common)) for seed, v in by_seed.items()})


def selection_shares(selections_root: Path) -> dict:
    """Countdown share of the 256 problems each arm selected per round (GradAlign Table 2 quantity)."""
    shares = {}
    for mode, _, _, _ in ARMS:
        rounds = {}
        for f in sorted(require_dir(selections_root / mode).glob("iter_*_256/train.jsonl")):
            r = int(f.parent.name.split("_")[1])
            counts: dict = {}
            payload = f.read_bytes()
            for line in payload.splitlines():
                src = json.loads(line)["data_source"]
                counts[src] = counts.get(src, 0) + 1
            if sum(counts.values()) != SELECTED_PER_ROUND or set(counts) - set(POOL_COUNTS):
                raise ValueError(f"Unexpected selected set in {f}: {counts}")
            rounds[r] = dict(step=SELECTION_INTERVAL * r, counts=counts,
                             countdown_share=counts.get("countdown", 0) / SELECTED_PER_ROUND,
                             path=relative(f, selections_root), sha256=sha256_bytes(payload))
        if not rounds or sorted(rounds) != list(range(len(rounds))):
            raise ValueError(f"Rounds must be contiguous from 0 for {mode}: {sorted(rounds)}")
        shares[mode] = [rounds[r] for r in sorted(rounds)]
    return dict(definition="Countdown share of the 256 problems selected at the start of each round; round r is selected at step 10r",
                pool_share=POOL_COUNTS["countdown"] / sum(POOL_COUNTS.values()), pool_counts=POOL_COUNTS,
                paper_reference=dict(label="GradAlign, paper Table 2 (own pool draw)", points=[[0, 92.9], [50, 62.1]]),
                per_arm=shares)


def training_packet(events_root: Path, selections_root: Path) -> dict:
    """Payload of Figure 6: seed-42 arms, seed-43 replicates, seed means, selection shares."""
    rows = {mode: dict(label=label, color=color, style=style, seed=42,
                       **load_events(events_root / "seed42" / mode, events_root))
            for mode, label, color, style in ARMS}
    comparisons = {}
    for mode, _, _, _ in ARMS:
        comparisons[mode + "_seed43"] = dict(label=rows[mode]["label"], color=rows[mode]["color"],
                                             style=rows[mode]["style"], seed=43,
                                             **load_events(events_root / "seed43" / mode, events_root))
    if any(not COMPARISON_REQUIRED_STEPS.issubset({p["step"] for p in row["points"]}) for row in comparisons.values()):
        raise ValueError("The comparison runs require every planned evaluation through step 30")
    display = {mode: dict(label=row["label"], color=row["color"], style=row["style"],
                          **average_runs([row, comparisons[mode + "_seed43"]]))
               for mode, row in rows.items()}
    common = sorted(set.intersection(*[{p["step"] for p in row["points"]} for row in display.values()]))
    if len(common) < 2:
        raise ValueError("At least two matched evaluation steps are required for a learning curve")
    runs_per_arm = {mode: len(row["seeds"]) for mode, row in display.items()}
    protocol = dict(task="GradAlign Scenario 2, local Countdown instance draw", model="Qwen2.5-Math-1.5B-Instruct",
                    evaluation_split="countdown4_test", evaluation_problems=500, evaluation_samples_per_problem=16,
                    metric_tag=EVAL_TAG, metric="Mean correctness over sampled responses; not pass@16",
                    head_feature="Advantage-weighted output-matrix gradient, two-sided 64 x 128 projection (GRADALIGN_PROD_SKETCH=1)",
                    training_runs_per_arm=runs_per_arm, display="Seed means at shared completed evaluation steps",
                    step_zero="Omitted: the available base measurement uses a different split",
                    status=f"Seed-averaged comparison available through step {common[-1]}",
                    replay_rule="Last wall-time evaluation per step from the resumed run; all superseded values retained; never average replays as independent seeds",
                    plotted_training_runs_per_arm=dict(runs_per_arm), figure_panels=["held_out_accuracy"],
                    figure_layout="half-page, paired RL figures", **producer_record())
    scope = "Head/full averaged over two seeds; shared 30-step horizon"
    return dict(
        schema_version=1, protocol=protocol, common_steps=common, arms=rows,
        seed_averages=dict(arms=display, common_steps=common,
                           rule="Equal-weight arithmetic mean over distinct training seeds at shared completed steps; no interpolation",
                           scope="; ".join(f"{row['label']}: seeds {', '.join(map(str, row['seeds']))}" for row in display.values())),
        selection_shares=selection_shares(selections_root),
        comparisons=dict(arms=comparisons, common_steps=sorted(COMPARISON_REQUIRED_STEPS),
                         exact_seed_means={key: display[key] for key in ("prod", "full")}, scope=scope))


def step_value(row: dict, step: int) -> float:
    """Accuracy in percent of one run or seed mean at one evaluation step."""
    return 100 * next(p for p in row["points"] if p["step"] == step)["value"]


def training_numbers(packet: dict) -> dict:
    """The Figure 6 numbers quoted in the paper, from the payload."""
    display = packet["seed_averages"]["arms"]
    steps, last = packet["common_steps"], packet["common_steps"][-1]
    random_final = step_value(display["rand"], last)
    first_reach = {mode: next((s for s in steps if step_value(row, s) >= random_final), None) for mode, row in display.items()}
    per_seed = {mode: {seed: 100 * v for seed, v in next(p for p in row["points"] if p["step"] == last)["values_by_seed"].items()}
                for mode, row in display.items()}
    return dict(final_step=last, final_mean={mode: step_value(row, last) for mode, row in display.items()},
                final_per_seed=per_seed,
                final_sample_std={mode: 100 * next(p for p in row["points"] if p["step"] == last)["sample_std"]
                                  for mode, row in display.items()},
                random_final=random_final, first_step_reaching_random_final=first_reach,
                fewer_steps_fraction=1 - first_reach["prod"] / last,
                pool_countdown_share=packet["selection_shares"]["pool_share"])



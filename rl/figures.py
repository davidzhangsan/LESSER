#!/usr/bin/env python3
"""Regenerate every RL result of the LESSER paper from the logged data in ``data/rl``.

This is the tier-1 reproduction: no GPU, no model weights and no training. It reads TensorBoard
scalars, saved selections and audit records, recomputes the reported numbers, and redraws the two RL
figures as vector PDFs. Each figure embeds its data payload in the PDF ``Subject`` field; the
payload matches the one embedded in the paper figure (compare with ``verify``).

Subcommands and the paper results they produce:

  corrupted  Figure 5 and Finding 3. Share of corrupted problems among the 128 problems selected from 512
             DAPO candidates (Qwen3-8B-Base, 64 responses each): LESSER 29.7% (38), full gradients 27.3%
             (35), AccGreedy 86.7% (111), Random 50% (64 expected).
  training   Figure 6 and Finding 4. Held-out Countdown accuracy over GRPO steps, two-seed means: step-50
             accuracy LESSER 32.46 and full gradients 32.46; LESSER reaches Random's final accuracy (29.79)
             at step 15, 70% fewer GRPO steps. Also the 11.8% Countdown share of the pool. LESSER uses
             the projected feature (64 x 128 two-sided sketch) in both figures.
  agreement  Appendix F.4 (RL statistics). First selection round: 1,835 of 5,120 problems with nonzero
             advantage; Spearman 0.69 between LESSER and full-gradient scores; the top 256 share 69% of
             their problems, Jaccard 0.53 against 0.075 for two random selections.
  all        Run the three subcommands, then compare both figure payloads and the RL numbers printed in
             the paper with ``data/rl/expected``; exits non-zero on any difference.
  verify     Compare the payload of a regenerated figure (PDF or JSON) with a reference payload (PDF or
             JSON); with two PDFs, also compare the drawn page content.

Example (from the repository root):

    python rl/figures.py all                       # writes outputs/rl/, exits non-zero on any mismatch
    python rl/figures.py verify outputs/rl/figure6_countdown_training.pdf <paper figure 6>.pdf

The RL cost numbers (FLOPs, feature storage and scoring wall clock of the cost table) are regenerated by
``python -m cost.rl_flops`` and ``python -m cost.timing_rl.parse_logs``.

Dependencies: numpy, reportlab (figures), tensorboard (event files), pypdf (``verify`` on PDFs only).
Missing or inconsistent inputs raise; nothing falls back to defaults.
"""

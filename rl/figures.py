def draw_rl_vector_pdf(packet: dict, output: Path, *, noisy: bool = False) -> str:
    """Draw one of the paired main RL panels directly as PDF paths and text (paper Figures 5 and 6).

    No raster rendering or smoothing: the training panel connects the recorded seed means at their
    actual evaluation steps. Both panels share one canvas size, plot baseline and top edge. The packet
    is embedded as JSON in the PDF Subject field.
    """
    from reportlab.lib.colors import HexColor
    from reportlab.pdfgen import canvas

    if output.suffix != ".pdf":
        raise ValueError("The vector RL panel must be a PDF")
    width, height = 190.08, 145.44
    bottom, top = 32, 112
    pdf = canvas.Canvas(str(output), pagesize=(width, height), pageCompression=1, invariant=1)
    pdf.setAuthor("anonymous")
    pdf.setTitle("Corrupted share of selected problems" if noisy else "Countdown RL training")
    pdf.setSubject(json.dumps(packet, sort_keys=True))
    pdf.setLineCap(1)
    pdf.setLineJoin(1)

    def text(x, y, value, *, size=8.5, color="#405464", align="left"):
        pdf.setFillColor(HexColor(color))
        pdf.setFont("Helvetica", size)
        draw = {"left": pdf.drawString, "center": pdf.drawCentredString, "right": pdf.drawRightString}[align]
        draw(x, y, value)

    def line(x1, y1, x2, y2, *, color="#E8EDF1", weight=.5):
        pdf.setStrokeColor(HexColor(color))
        pdf.setLineWidth(weight)
        pdf.setDash()
        pdf.line(x1, y1, x2, y2)

    if noisy:
        # The axis runs to 110% so every value label sits after its bar and inside the axis range;
        # a white box behind each label keeps the 100% gridline from striking through it.
        left, right, axis_max = 62, 180, 110
        rows = packet["measurements"]["rows"]
        if len(rows) != 4:
            raise ValueError("The corrupted-reward panel requires four selectors")
        for tick in (0, 50, 100):
            x = left + (right - left) * tick / axis_max
            line(x, bottom, x, top)
            text(x, bottom - 13, str(tick), align="center")
        for index, row in enumerate(rows):
            value = row["corrupted_percent"]
            if not 0 < value <= 100:
                raise ValueError(f"Invalid corrupted share: {value}")
            y = top - (index + .5) * (top - bottom) / len(rows)
            text(left - 7, y - 3, row["label"], size=8, align="right")
            length = (right - left) * value / axis_max
            pdf.setFillColor(HexColor(RL_METHOD_COLORS[row["method"]]))
            pdf.roundRect(left, y - 5, length, 10, radius=2.5, stroke=0, fill=1)
            label = f"{value:.1f}"
            label_x, label_width = left + length + 5, pdf.stringWidth(label, "Helvetica", 9)
            if label_x + label_width > right:
                raise ValueError(f"Value label {label} would extend past the axis")
            pdf.setFillColor(HexColor("#FFFFFF"))
            pdf.rect(label_x - 1.5, y - 5.5, label_width + 3, 11, stroke=0, fill=1)
            text(label_x, y - 3, label, size=9, color="#1C2B37")
        line(left, bottom, right, bottom, color="#92A1AF", weight=.6)
        text((left + right) / 2, 6, "Corrupted share (%)", size=9, color="#1C2B37", align="center")
    else:
        left, right = 37, 183
        rows = packet["seed_averages"]["arms"]
        steps = packet["common_steps"]
        if set(rows) != {"prod", "full", "acc", "rand"} or len(steps) < 2:
            raise ValueError("The training panel requires four seed-averaged selectors")
        points = {key: {p["step"]: 100 * p["value"] for p in row["points"]} for key, row in rows.items()}
        values = [points[key][step] for key in rows for step in steps]
        lo, hi = 5 * np.floor(min(values) / 5), 5 * np.ceil(max(values) / 5)
        if hi <= lo:
            raise ValueError("Training curves must have a nonzero vertical range")
        xcoord = lambda step: left + (right - left) * (step - steps[0]) / (steps[-1] - steps[0])  # noqa: E731
        ycoord = lambda value: bottom + (top - bottom) * (value - lo) / (hi - lo)  # noqa: E731
        for tick in np.arange(lo, hi + .01, 10 if hi - lo >= 20 else 5):
            y = ycoord(tick)
            line(left, y, right, y)
            text(left - 6, y - 3, f"{tick:g}", align="right")
        for tick in steps:
            if tick % 10 == 0:
                x = xcoord(tick)
                line(x, bottom, x, bottom - 2, color="#92A1AF", weight=.6)
                text(x, bottom - 13, str(tick), align="center")
        line(left, bottom, right, bottom, color="#92A1AF", weight=.6)
        line(left, bottom, left, top, color="#92A1AF", weight=.6)
        text((left + right) / 2, 6, "GRPO training steps", size=9, color="#1C2B37", align="center")
        pdf.saveState()
        pdf.translate(9, (bottom + top) / 2)
        pdf.rotate(90)
        text(0, 0, "Test pass@1 (%)", size=9, color="#1C2B37", align="center")
        pdf.restoreState()
        styles = {"prod": (RL_METHOD_COLORS["head"], 1.8, ()),
                  "full": (RL_METHOD_COLORS["full"], 1.1, (4, 2.4)),
                  "acc": (RL_METHOD_COLORS["acc"], 1.3, ()),
                  "rand": (RL_METHOD_COLORS["rand"], 1.3, (1, 2.5))}
        for key in ("rand", "acc", "prod", "full"):
            color, weight, dash = styles[key]
            pdf.setStrokeColor(HexColor(color))
            pdf.setLineWidth(weight)
            pdf.setDash(dash)
            path = pdf.beginPath()
            path.moveTo(xcoord(steps[0]), ycoord(points[key][steps[0]]))
            for step in steps[1:]:
                path.lineTo(xcoord(step), ycoord(points[key][step]))
            pdf.drawPath(path)
            pdf.setDash()
        for index, key in enumerate(("prod", "full", "acc", "rand")):
            x, y = right - 80, bottom + 33 - index * 9.5  # the late-step curves leave this region empty
            color, weight, dash = styles[key]
            pdf.setStrokeColor(HexColor(color))
            pdf.setLineWidth(weight)
            pdf.setDash(dash)
            pdf.line(x, y, x + 10, y)
            pdf.setDash()
            label = rows[key]["label"].replace("Full policy gradient", "Full gradients")
            text(x + 14, y - 3, label, size=7.8, color="#1C2B37")
    pdf.showPage()
    pdf.save()
    return str(output)


# ------------------------------------------------------------------------------ Figure 5: corrupted
def read_jsonl_recorded(path: Path, root: Path, sources: list) -> list:
    payload = require_file(path).read_bytes()
    sources.append(dict(path=relative(path, root), sha256=sha256_bytes(payload)))
    return [json.loads(line) for line in payload.splitlines()]


def corrupted_measurements(pool: list, accuracies: dict, selections: dict) -> dict:
    """Corrupted shares of the saved LESSER and full-gradient selections, AccGreedy and Random.

    Rejects anything but the completed balanced 512-candidate pool with 64 responses per candidate.
    """
    labels = {}
    for row in pool:
        index, corrupted = row["extra_info"]["index"], row["extra_info"]["corrupted"]
        if type(index) is not int or type(corrupted) is not bool or index in labels:
            raise ValueError("Invalid or duplicate corrupted-pool record")
        labels[index] = corrupted
    if len(labels) != 512 or sum(labels.values()) != 256:
        raise ValueError("Expected the balanced 512-candidate pool with 256 corrupted problems")
    if set(accuracies) != {"head", "full"} or set(selections) != {"head", "full"}:
        raise ValueError("Both LESSER (head) and full-gradient records are required")
    rates = {}
    for method, rows in accuracies.items():
        rates[method] = {}
        for row in rows:
            index, total, correct = row["group_id"], row["total"], row["correct"]
            if (index not in labels or index in rates[method] or total != 64 or type(correct) is not int
                    or not 0 <= correct <= total or row["accuracy"] != correct / total):
                raise ValueError("Invalid, duplicate, or non-64-response reward record")
            rates[method][index] = correct / total
        if set(rates[method]) != set(labels):
            raise ValueError("Reward records do not cover every candidate")
    if rates["head"] != rates["full"]:
        raise ValueError("LESSER and full-gradient runs must score the same rollouts")
    measurements = []
    for method, label in (("head", "LESSER"), ("full", "Full gradients")):
        ids = [row["extra_info"]["index"] for row in selections[method]]
        if len(ids) != 128 or len(set(ids)) != 128 or not set(ids) <= set(labels):
            raise ValueError("Expected 128 distinct selected candidates")
        if any(row["extra_info"]["corrupted"] != labels[row["extra_info"]["index"]] for row in selections[method]):
            raise ValueError("Selected-set corruption labels differ from the pool")
        count = sum(labels[i] for i in ids)
        measurements.append(dict(method=method, label=label, selected_ids=ids, corrupted_count=count,
                                 corrupted_percent=100 * count / 128, kind="saved_selection"))
    # AccGreedy: the 128 mixed-reward candidates whose reward rate is closest to 0.5. The sort is stable,
    # so ties keep the order of the LESSER accuracy file.
    live = [row["group_id"] for row in accuracies["head"] if 0 < row["accuracy"] < 1]
    if len(live) < 128:
        raise ValueError("Fewer than 128 mixed-reward candidates for AccGreedy")
    greedy = sorted(live, key=lambda i: abs(rates["head"][i] - .5))[:128]
    count = sum(labels[i] for i in greedy)
    measurements.append(dict(method="acc", label="AccGreedy", selected_ids=greedy, corrupted_count=count,
                             corrupted_percent=100 * count / 128, kind="offline_selection"))
    measurements.append(dict(method="rand", label="Random", corrupted_percent=100 * sum(labels.values()) / len(labels),
                             kind="uniform_random_expectation"))
    return dict(candidates=len(labels), selected_per_method=128, responses_per_candidate=64,
                mixed_reward_candidates=len(live), rows=measurements)


def corrupted_packet(root: Path) -> dict:
    """Payload of Figure 5 from <root>/subpool/train.jsonl and <root>/{head,full}/ (LESSER, full gradients)."""
    root = require_dir(root)
    sources: list = []
    pool = read_jsonl_recorded(root / "subpool/train.jsonl", root, sources)
    accuracies = {m: read_jsonl_recorded(root / f"{m}/accuracy_by_problem.jsonl", root, sources)
                  for m in ("head", "full")}
    selections = {m: read_jsonl_recorded(root / f"{m}/selected/iter_0_{mode}_128/train.jsonl", root, sources)
                  for m, mode in (("head", "prod"), ("full", "sim"))}
    protocol = dict(setting="Scenario 1, local balanced DAPO subsample, initial selection only",
                    metric="Corrupted share of selected problems; lower is better",
                    accgreedy="Top 128 mixed-reward candidates closest to reward rate 0.5; ties retain head accuracy-file order",
                    random="Expected corrupted share under uniform selection from all 512 candidates",
                    uncertainty="One candidate subset and response draw; bars are descriptive, not confidence intervals",
                    figure_layout="half-page, paired RL figures", **producer_record())
    return dict(schema_version=1, measurements=corrupted_measurements(pool, accuracies, selections),
                protocol=protocol, sources=sources)



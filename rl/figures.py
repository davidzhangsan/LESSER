def spearman(x: np.ndarray, y: np.ndarray) -> float:
    """Spearman rank correlation with average ranks for ties."""
    def rank(a):
        order = np.argsort(a, kind="stable")
        ranks = np.empty(len(a), dtype=np.float64)
        sorted_a = a[order]
        i = 0
        while i < len(a):
            j = i
            while j + 1 < len(a) and sorted_a[j + 1] == sorted_a[i]:
                j += 1
            ranks[order[i:j + 1]] = (i + j) / 2.0
            i = j + 1
        return ranks
    rx, ry = rank(np.asarray(x, dtype=np.float64)), rank(np.asarray(y, dtype=np.float64))
    return float(np.corrcoef(rx, ry)[0, 1])


def run_agreement(audit_files: list, accuracy_path: Path, out_dir: Path, selection_count: int = 256) -> dict:
    """LESSER versus full-gradient scores on every nonzero-advantage problem of the first round.

    Inputs: the base-policy audit records (data/rl/countdown/audit; the audit script is not distributed;
    the paper ran it as a 615-problem subset and its 1,220-problem complement, three shards each), which
    recomputes both cosines in FP32 from 16 responses per problem, and the round-0 accuracy file, which
    defines the nonzero-advantage problems. Top-k sets use a stable sort; ties do not occur in the paper data.
    """
    rows, meta = {}, []
    for path in audit_files:
        shard = json.loads(require_file(path).read_text())
        if not shard["complete"] or shard["n_done"] != len(shard["results"]):
            raise ValueError(f"Incomplete audit file {path}")
        meta.append((shard["n_live_groups"], shard["n_groups"], shard["mini_batch_size"]))
        for r in shard["results"]:
            if r["group_id"] in rows:
                raise ValueError(f"Group {r['group_id']} appears in two audit files")
            if r["n_responses"] != 16:
                raise ValueError("Every audited problem must have 16 responses")
            rows[r["group_id"]] = r
    if len(set(meta)) != 1:
        raise ValueError(f"Audit shards disagree on their population: {sorted(set(meta))}")
    n_live, n_groups, mbs = meta[0]
    accuracy = [json.loads(line) for line in require_file(accuracy_path).read_text().splitlines()]
    live = {r["group_id"] for r in accuracy if 0 < r["accuracy"] < 1}
    if len(accuracy) != n_groups or set(rows) != live or len(live) != n_live:
        raise ValueError("Audited problems must be exactly the nonzero-advantage problems of round 0")
    ids = sorted(rows)
    head = np.array([rows[g]["cos_head"] for g in ids])
    full = np.array([rows[g]["cos_full"] for g in ids])
    rho = spearman(head, full)
    top = lambda s: set(np.argsort(-s, kind="stable")[:selection_count].tolist())  # noqa: E731
    shared = len(top(head) & top(full))
    jaccard = shared / (2 * selection_count - shared)
    p = selection_count / len(ids)
    numbers = dict(candidates=n_groups, nonzero_advantage=len(ids), responses_per_problem=16, analysis_mini_batch=mbs,
                   spearman=rho, selection_count=selection_count, budget_fraction=p, shared=shared,
                   shared_fraction=shared / selection_count, jaccard=jaccard, random_jaccard=p / (2 - p))
    write_json(out_dir / "appendix_f4_rl_agreement.json", numbers)
    print("Appendix F.4, RL (first selection round, base policy, FP32 audit)")
    print(f"  problems with nonzero advantage: {len(ids):,} of {n_groups:,}")
    print(f"  Spearman correlation of LESSER and full-gradient scores: {rho:.3f}")
    print(f"  top {selection_count} ({100 * p:.0f}% of {len(ids):,}): {shared} shared = {100 * shared / selection_count:.1f}%, "
          f"Jaccard {jaccard:.3f}; two random selections p/(2-p) = {p / (2 - p):.3f}")
    return numbers



def payload_from(path: Path):
    """The figure payload of a PDF (Subject field) or a JSON manifest; None for a PDF without one."""
    if path.suffix == ".pdf":
        from pypdf import PdfReader
        metadata = PdfReader(str(require_file(path))).metadata or {}
        return json.loads(metadata["/Subject"]) if "/Subject" in metadata else None
    return json.loads(require_file(path).read_text())


def _tail(path: str, markers: set) -> str:
    parts = PurePosixPath(path).parts
    index = max(i for i, part in enumerate(parts) if part in markers)
    return "/".join(parts[index:])


EVENT_FILE_NAME = re.compile(r"(events\.out\.tfevents\.\d+)\.(.+)\.(\d+)\.(\d+)")


def event_file_name(name: str) -> str:
    """TensorBoard names event files events.out.tfevents.<time>.<host>.<pid>.<n>. The released copies
    in data/rl carry the host name ``node``; payloads are compared with every host name replaced by it."""
    match = EVENT_FILE_NAME.fullmatch(name)
    if match is None:
        raise ValueError(f"Not a TensorBoard event file name: {name}")
    return f"{match.group(1)}.node.{match.group(3)}.{match.group(4)}"


def normalize_payload(payload: dict) -> dict:
    """Drop producer, command and output locations; reduce input paths to their machine-independent tail.

    Event file names keep their time stamp, process id and counter; their host name becomes ``node``.
    """
    p = copy.deepcopy(payload)
    for key in ("figure", "figures"):
        p.pop(key, None)
    for key in ("producer", "producer_sha256", "command"):
        p.get("protocol", {}).pop(key, None)
    if "measurements" in p:  # Figure 5
        for source in p["sources"]:
            source["path"] = _tail(source["path"], {"subpool", "head", "full"})
        return p
    p.get("comparisons", {}).pop("figure", None)
    for row in list(p.get("arms", {}).values()) + list(p.get("comparisons", {}).get("arms", {}).values()):
        for source in row["sources"]:
            source["path"] = event_file_name(PurePosixPath(source["path"]).name)
        for point in row["points"] + row["superseded"]:
            point["source"] = event_file_name(point["source"])
    for rounds in p.get("selection_shares", {}).get("per_arm", {}).values():
        for entry in rounds:
            entry["path"] = "/".join(PurePosixPath(entry["path"]).parts[-3:])
    return p


def payload_differences(a, b, path="") -> list:
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for key in sorted(set(a) | set(b)):
            if key not in a or key not in b:
                out.append(f"{path}/{key}: present in only one payload")
            else:
                out += payload_differences(a[key], b[key], f"{path}/{key}")
        return out
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        if len(a) != len(b):
            return [f"{path}: length {len(a)} != {len(b)}"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in payload_differences(x, y, f"{path}[{i}]")]
    return [] if a == b else [f"{path}: {str(a)[:60]} != {str(b)[:60]}"]


def page_contents(path: Path) -> list:
    from pypdf import PdfReader
    return [page.get_contents().get_data() for page in PdfReader(str(path)).pages]


def verify(regenerated: Path, reference: Path) -> tuple:
    """Differences between two figures, and a description of what was compared.

    Payloads are compared after ``normalize_payload``. When both files are PDFs the drawn page content is
    compared too; a reference PDF whose metadata was stripped (as in the anonymized paper sources) is
    compared by page content only.
    """
    ours, theirs = payload_from(regenerated), payload_from(reference)
    if ours is None:
        raise ValueError(f"{regenerated} carries no payload; regenerate it with this script")
    differences, compared = [], []
    if theirs is not None:
        differences += payload_differences(normalize_payload(ours), normalize_payload(theirs))
        compared.append("payload")
    if regenerated.suffix == reference.suffix == ".pdf":
        if page_contents(regenerated) != page_contents(reference):
            differences.append("drawn page content differs")
        compared.append("drawn page content")
    if not compared:
        raise ValueError("Nothing to compare")
    return differences, " and ".join(compared)


def printed(value: float, template: str) -> str:
    """Round `value` the way the paper prints `template`: fixed decimals, or scientific such as 3.11e9."""
    if "e" in template:
        mantissa = template.split("e")[0]
        digits = len(mantissa.split(".")[1]) if "." in mantissa else 0
        m, e = f"{value:.{digits}e}".split("e")
        return f"{m}e{int(e)}"
    digits = len(template.split(".")[1]) if "." in template else 0
    return f"{value:.{digits}f}"


